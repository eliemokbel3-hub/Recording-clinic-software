def _bundle(release: ModuleType, root: Path) -> Path:
    bundle = root / "dist" / "scribe"
    for exe in ("scribe-app.exe", "scribe-host.exe"):
        (bundle / exe).parent.mkdir(parents=True, exist_ok=True)
        (bundle / exe).write_bytes(b"MZ")
    defaults = REPO / "desktop" / "src" / "scribe_desktop" / "config_defaults"
    target = bundle / "_internal" / "scribe_desktop" / "config_defaults"
    target.mkdir(parents=True)
    for file in defaults.glob("*.json"):
        (target / file.name).write_bytes(b"{}")
    for folder in release.NATIVE_LIBRARY_DIRS:
        (bundle / "_internal" / folder).mkdir(parents=True, exist_ok=True)
        (bundle / "_internal" / folder / "lib.dll").write_bytes(b"MZ")
    (bundle / "_internal" / "PySide6").mkdir()
    (bundle / "_internal" / "PySide6" / "Qt6Core.dll").write_bytes(b"MZ")
    return bundle


