def _names(word: str) -> set[str]:
    """What a key may match in one command word: the word itself, and the name
    and stem of its last path part (``ISCC`` for ``…\\ISCC.exe``) — NEVER a
    substring of a path, so a temporary folder named after the test (pytest's
    ``…_status0``) can never answer for another command (round 20 fix-delta)."""
    name = PureWindowsPath(word).name
    return {word, name, PureWindowsPath(name).stem}


class _Runner:
    """Records every command; answers with the code ``codes`` maps a key to
    (default 0), ``outputs`` its stdout and ``errors`` its stderr — a key
    matching one WORD of the command (``_names``), never part of a path."""

    def __init__(
        self,
        codes: dict[str, int] | None = None,
        outputs: dict[str, str] | None = None,
        errors: dict[str, str] | None = None,
    ) -> None:
        self.commands: list[list[str]] = []
        self.envs: list[dict[str, str] | None] = []
        self.codes = codes or {}
        self.outputs = outputs or {}
        self.errors = errors or {}

    def __call__(self, command: Any, **kwargs: Any) -> Any:
        words = [str(part) for part in command]
        self.commands.append(words)
        self.envs.append(kwargs.get("env"))
        names = set().union(*(_names(word) for word in words))
        code = next((v for k, v in self.codes.items() if k in names), 0)
        out = next((v for k, v in self.outputs.items() if k in names), "")
        err = next((v for k, v in self.errors.items() if k in names), "")
        return SimpleNamespace(returncode=code, stdout=out, stderr=err)


