def _load(stem: str) -> ModuleType:
    """A hyphenated script as a module. Registered in ``sys.modules`` first:
    ``dataclasses`` resolves a string annotation through the defining
    module's entry there."""
    path = REPO / "scripts" / f"{stem}.py"
    name = f"{stem.replace('-', '_')}_under_test"
    spec = importlib.util.spec_from_file_location(name, path)
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    sys.modules[name] = module
    spec.loader.exec_module(module)
    return module


